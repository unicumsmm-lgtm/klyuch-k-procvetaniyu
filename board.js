function shuffle(arr) {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

// Собирает новую доску на основе PATH: каждой клетке типа "card"
// присваивается случайная колода из 24 (без повторов, пока хватает).
export function buildBoard() {
  const cardCells = PATH.filter((c) => c.type === 'card')
  const shuffledDecks = shuffle(DECK_NAMES).slice(0, cardCells.length)

  let deckIndex = 0
  return PATH.map((cell, i) => {
    if (cell.type !== 'card') return { ...cell, id: `cell_${i}` }
    const deck = shuffledDecks[deckIndex]
    deckIndex++
    return { ...cell, deck, id: `cell_${i}` }
  })
}
