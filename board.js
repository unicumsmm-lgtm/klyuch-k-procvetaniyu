// это уже упрощённая квадратная версия "Поле2.png"). Фишка двигается по
// реальным координатам клеток на этой картинке (x/y в процентах).
//
// Координаты для внешних двух колец сняты через программный анализ
// границ клеток на картинке (сетка 16×16 клеток по периметру, точные
// проценты краёв), для внутренних колец и центра — вручную по сетке-
// разметке, наложенной на скан. Маршрут идёт по часовой стрелке: старт
// слева на внешнем кольце → вниз → направо по нижнему ряду → внутрь на
// следующее кольцо, и так до центра ("Ключ").
//
// Для компактного пилота (максимум ~10 ходов) выбрано по 2-3 настоящих
// клетки на каждое из 4 колец — это не все ~200 клеток настоящего поля,
// а показательный маршрут по нему (так и обсуждали с Рамилем).
//
// Какая из 24 колод "живёт" на каждой клетке — решается случайно при
// каждом старте партии (см. buildBoard) — жёсткой привязки иконка→колода нет.

