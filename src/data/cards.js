// Выбирает случайный вариант напутствия для данного mode, которого ещё не
// было в этой партии (usedTexts — уже показанные тексты). Если пул
// исчерпан (не должно случиться при 5 ходах, но на всякий случай),
// разрешаем повтор, чтобы функция никогда не возвращала пустоту.
export function pickGuidance(mode, usedTexts = []) {
  const pool = GUIDANCE_POOL[mode] || GUIDANCE_POOL.positive
  const unused = pool.filter((text) => !usedTexts.includes(text))
  const options = unused.length > 0 ? unused : pool
  return options[Math.floor(Math.random() * options.length)]
}

export function getQuestionsForDeck(deckName) {
  const deck = DECKS[deckName]
  if (!deck) return []
  if (deck.mode === 'negative') return NEGATIVE_QUESTIONS[deckName] || []
  if (deck.mode === 'positive') return UNIVERSAL_QUESTIONS
  return []
}

function shuffle(arr) {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

// Выбирает N (по умолчанию 5) РАЗНЫХ колод для одной партии — порядок ходов.
export function pickGameDecks(count = 5) {
  return shuffle(DECK_NAMES).slice(0, count)
}

// Достаёт ВСЕ карточки колоды (перемешанные) для показа рубашкой вверх —
// без ограничения по количеству (раньше был лимит 24, убран по просьбе
// Рамиля). Вопросы и напутствие берутся на уровне колоды (getQuestionsForDeck
// / GUIDANCE в CardScreen.jsx), а не на уровне конкретной карты, так что
// каждая из карт — включая все 35 у самой большой колоды — уже полностью
// покрыта существующей логикой, без необходимости дописывать что-то новое.
export function drawFullDeck(deckName) {
  const deck = DECKS[deckName]
  if (!deck) return []
  return shuffle(deck.titles).map((title, i) => ({
    id: `${deckName}__${i}`,
    deckName,
    title,
    mode: deck.mode,
    symbol: deck.symbol,
    color: deck.color,
    cover: deck.cover,
  }))
}

// Простая эвристика: проверяет, что ответ похож на осмысленный текст, а не
// на случайный набор букв/цифр или пустую отписку.
export function isAnswerSubstantive(text) {
  const trimmed = (text || '').trim()
  if (trimmed.length < 8) return false

  const letters = trimmed.match(/[a-zA-Zа-яА-ЯёЁ]/g) || []
  if (letters.length < 6) return false

  const words = trimmed.split(/\s+/).filter((w) => w.length > 1)
  if (words.length < 2) return false

  // Отсекаем "бессмысленный" набор символов вроде "асдасдасд" или "1111111"
  const uniqueChars = new Set(trimmed.toLowerCase().replace(/\s/g, '')).size
  if (uniqueChars < 5) return false

  // Отсекаем повторяющееся одно и то же слово ("да да да да")
  const uniqueWords = new Set(words.map((w) => w.toLowerCase()))
  if (uniqueWords.size < Math.min(2, words.length)) return false

  return true
}
